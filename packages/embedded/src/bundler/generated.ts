import { createHash } from "node:crypto";

import { withEmbeddedComponentTables, type EmbeddedSchemaAnalysis } from "../schema";
import type { StoreSchema } from "../storage/types";
import type { EmbeddedBundleResult, EmbeddedFunctionManifestEntry } from "./index";

export const EMBEDDED_GENERATED_FORMAT_VERSION = 1;

export interface EmbeddedGeneratedInput {
  analysis: EmbeddedSchemaAnalysis;
  bundle: EmbeddedBundleResult;
}

export interface EmbeddedGeneratedSchema extends EmbeddedSchemaAnalysis {
  runtimeStoreSchema: StoreSchema;
}

/** Renders the checked-in/generated device contract without importing the live server schema. */
export function renderEmbeddedGenerated({ analysis, bundle }: EmbeddedGeneratedInput): string {
  const local = Object.fromEntries(
    Object.entries(bundle.manifest).flatMap(([moduleId, functions]) => {
      const entries = Object.entries(functions).filter(([, entry]) => entry.placement === "local");
      return entries.length ? [[moduleId, Object.fromEntries(entries)]] : [];
    }),
  );
  const localApi = renderApi(local);
  const localReferenceSupport = Object.keys(local).length
    ? `import { makeFunctionReference, type FunctionReference } from "convex/server";
import type { RegisteredMutation, RegisteredQuery } from "convex/server";

type LocalReference<Function> =
  Function extends RegisteredQuery<infer Visibility, infer Args, infer Returns>
    ? FunctionReference<"query", Visibility, Args, Returns>
    : Function extends RegisteredMutation<infer Visibility, infer Args, infer Returns>
      ? FunctionReference<"mutation", Visibility, Args, Returns>
      : never;
`
    : "";
  const embeddedSchema: EmbeddedGeneratedSchema = {
    ...analysis,
    runtimeStoreSchema: withEmbeddedComponentTables(analysis.storeSchema),
  };
  const identity = {
    analysisHash: hashJson(embeddedSchema),
    formatVersion: EMBEDDED_GENERATED_FORMAT_VERSION,
    manifestHash: bundle.manifestHash,
    schemaSourceHash: bundle.schemaSourceHash,
  };
  return `// @convex-dev/embedded-generated ${JSON.stringify(identity)}
/* eslint-disable */
// Generated by @convex-dev/embedded. Do not edit.
${localReferenceSupport}

export const embeddedGeneratedFormatVersion = ${EMBEDDED_GENERATED_FORMAT_VERSION} as const;
export const embeddedGeneratedIdentity = ${JSON.stringify(identity)} as const;
export const embeddedSchema = ${JSON.stringify(embeddedSchema)} as const;
export const embeddedManifest = ${JSON.stringify(bundle.manifest)} as const;
export const localApi = ${localApi};
`;
}

function hashJson(value: unknown): string {
  return createHash("sha256").update(JSON.stringify(value)).digest("hex").slice(0, 16);
}

function renderApi(modules: Record<string, Record<string, EmbeddedFunctionManifestEntry>>): string {
  const root: Record<string, unknown> = {};
  for (const [moduleId, functions] of Object.entries(modules)) {
    const segments = moduleId.split("/");
    let cursor = root;
    for (const segment of segments) {
      cursor = (cursor[segment] ??= {}) as Record<string, unknown>;
    }
    for (const [name, entry] of Object.entries(functions)) {
      cursor[name] = reference(moduleId, name, entry);
    }
  }
  return renderObject(root);
}

function reference(
  moduleId: string,
  name: string,
  entry: EmbeddedFunctionManifestEntry,
): { source: string } {
  return {
    source: `(makeFunctionReference<${JSON.stringify(entry.kind)}>(${JSON.stringify(
      `${moduleId}:${name}`,
    )}) as LocalReference<typeof import(${JSON.stringify(`../${moduleId}`)})[${JSON.stringify(
      name,
    )}]>)`,
  };
}

function renderObject(value: Record<string, unknown>): string {
  const entries = Object.entries(value).map(([key, child]) => {
    const rendered =
      typeof child === "object" && child !== null && "source" in child
        ? (child as { source: string }).source
        : renderObject(child as Record<string, unknown>);
    return `${JSON.stringify(key)}: ${rendered}`;
  });
  return `{ ${entries.join(", ")} }`;
}
