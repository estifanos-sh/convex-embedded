import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const descriptor = JSON.parse(readFileSync(resolve(root, "protocol/embedded.json"), "utf8"));
const surface = JSON.parse(readFileSync(resolve(root, "protocol/embedded.surface.json"), "utf8"));
const { blob, surface: wireSurface } = validateDescriptor(descriptor, surface);
const id = contractId(descriptor);
const update = process.argv.includes("--update");
const sourceMutation = readSourceMutation();
const browser = validateSemanticDescriptor("browser", browserSurface());
const mobile = validateSemanticDescriptor("mobile", mobileSurface());
const storage = validateSemanticDescriptor("storage", storageSurface());
const browserId = contractId(browser);
const mobileId = contractId(mobile);
const storageId = contractId(storage);
const outputs = new Map([
  [
    resolve(root, "packages/embedded/src/contract/generated.ts"),
    `// Generated by packages/embedded/scripts/contract.mjs. Do not edit.\nexport const CURRENT_WIRE_CONTRACT_ID = ${JSON.stringify(id)} as const;\nexport const WIRE_BLOB_CHUNK_BYTES = ${blob.chunkBytes};\nexport const WIRE_BLOB_CLIENT_SCOPE_LIMIT = ${blob.clientScopes};\nexport const WIRE_BLOB_CLIENT_BYTE_LIMIT = ${blob.clientBytes};\nexport const WIRE_SURFACE = ${JSON.stringify(wireSurface, null, 2)} as const;\nexport const WIRE_ERROR_PROTOCOL_MISMATCH = WIRE_SURFACE.errors[0];\nexport type WireContractId = typeof CURRENT_WIRE_CONTRACT_ID;\n`,
  ],
  [
    resolve(root, "crates/storage/src/contract/generated.rs"),
    `// Generated by packages/embedded/scripts/contract.mjs. Do not edit.\npub const CURRENT_WIRE_CONTRACT_ID: &str =\n    ${JSON.stringify(id)};\npub const CURRENT_MOBILE_BRIDGE_CONTRACT_ID: &str =\n    ${JSON.stringify(mobileId)};\npub const CURRENT_STORAGE_BINDING_CONTRACT_ID: &str =\n    ${JSON.stringify(storageId)};\npub const WIRE_BLOB_CHUNK_BYTES: usize = ${rustInteger(blob.chunkBytes)};\npub const WIRE_BLOB_CLIENT_SCOPE_LIMIT: usize = ${rustInteger(blob.clientScopes)};\npub const WIRE_BLOB_CLIENT_BYTE_LIMIT: usize = ${rustInteger(blob.clientBytes)};\npub const WIRE_ENDPOINT_PULL: &str = ${JSON.stringify(wireSurface.endpoints.pull)};\npub const WIRE_ENDPOINT_PUSH: &str = ${JSON.stringify(wireSurface.endpoints.push)};\npub const WIRE_ENDPOINT_UPLOAD: &str = ${JSON.stringify(wireSurface.endpoints.upload)};\n`,
  ],
  [
    resolve(root, "packages/embedded/src/browser/coordinator/contract.ts"),
    `// Generated by packages/embedded/scripts/contract.mjs. Do not edit.\nexport const CURRENT_BROWSER_COORDINATION_CONTRACT_ID = ${JSON.stringify(browserId)} as const;\n`,
  ],
  [
    resolve(root, "packages/embedded/src/expo/contract.ts"),
    `// Generated by packages/embedded/scripts/contract.mjs. Do not edit.\nexport const CURRENT_MOBILE_BRIDGE_CONTRACT_ID = ${JSON.stringify(mobileId)} as const;\nexport const CURRENT_WIRE_CONTRACT_ID = ${JSON.stringify(id)} as const;\n`,
  ],
  [
    resolve(root, "packages/embedded/src/storage/contract.ts"),
    `// Generated by packages/embedded/scripts/contract.mjs. Do not edit.\nexport const CURRENT_STORAGE_BINDING_CONTRACT_ID = ${JSON.stringify(storageId)} as const;\n`,
  ],
]);
const check = process.argv.includes("--check");
let changed = false;
const changedPaths = [];
for (const [path, content] of outputs) {
  let existing = "";
  try {
    existing = readFileSync(path, "utf8");
  } catch {}
  if (!generatedEqual(path, existing, content)) {
    changed = true;
    changedPaths.push(path);
    if (!check) writeFileSync(path, content);
  }
}
if (!check && changed) {
  execFileSync("vp", ["fmt", ...[...outputs.keys()].filter((path) => path.endsWith(".ts"))], {
    cwd: root,
    stdio: "inherit",
  });
}
if (check && changed) {
  console.error(`Generated contract drift: ${changedPaths.join(", ")}`);
  process.exitCode = 1;
}

function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  return `{${Object.keys(value)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
    .join(",")}}`;
}

/** Format generated integer literals to satisfy Rust's readability lint. */
function rustInteger(value) {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new Error(`Expected a non-negative safe integer, received ${value}`);
  }
  return value.toLocaleString("en-US").replaceAll(",", "_");
}

function readDescriptor(name) {
  const value = JSON.parse(readFileSync(resolve(root, `protocol/${name}.json`), "utf8"));
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`protocol/${name}.json must be an object`);
  }
  if (typeof value.format !== "string" || !value.format.startsWith("convex-embedded-")) {
    throw new Error(`protocol/${name}.json must declare a Convex Embedded format`);
  }
  return value;
}

/**
 * The three local contracts deliberately derive their identities from the source that defines
 * their ABI. A short hand-written list is not a compatibility boundary: it inevitably misses
 * optional fields, nested worker frames, or one of the native operations.  Instead, TypeScript's
 * own parser prints the declaration closure rooted at each public boundary.  The closure follows
 * imported project declarations, which makes a change to (for example) WorkerRequest part of the
 * browser coordination identity without duplicating that type here.
 */
function validateSemanticDescriptor(name, semanticSurface) {
  const value = readDescriptor(name);
  const pointer = value.surface;
  if (!pointer || typeof pointer !== "object" || Array.isArray(pointer)) {
    throw new Error(`protocol/${name}.json must declare its generated semantic surface`);
  }
  if (pointer.algorithm !== "semantic-source/v2") {
    if (!update) {
      throw new Error(`protocol/${name}.json surface algorithm must be semantic-source/v2`);
    }
    pointer.algorithm = "semantic-source/v2";
  }
  const digest = `sha256:${createHash("sha256").update(canonicalJson(semanticSurface)).digest("hex")}`;
  if (pointer.digest !== digest) {
    if (!update) {
      throw new Error(
        `protocol/${name}.json semantic surface changed; run node packages/embedded/scripts/contract.mjs --update to record ${digest}`,
      );
    }
    pointer.digest = digest;
    writeFileSync(resolve(root, `protocol/${name}.json`), `${JSON.stringify(value, null, 2)}\n`);
  }
  return value;
}

