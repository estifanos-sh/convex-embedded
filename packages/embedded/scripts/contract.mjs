function mobileSurface() {
  const typescriptOperations = operationsIn(
    "packages/embedded/src/expo/store.ts",
    /this\.invoke(?:Remote)?(?:<[^>]+>)?\(\s*"([A-Za-z][A-Za-z0-9]*)"/g,
  );
  const rustOperations = operationsIn(
    "crates/mobile/src/lib.rs",
    /^\s*(?:operation\s*@\s*)?\(?((?:"[A-Za-z][A-Za-z0-9]*"\s*\|\s*)*"[A-Za-z][A-Za-z0-9]*")\)?\s*=>/gm,
    (match) => [...match[1].matchAll(/"([A-Za-z][A-Za-z0-9]*)"/g)].map((value) => value[1]),
  );
  const ts = new Set(typescriptOperations);
  const rust = new Set(rustOperations);
  if (ts.size !== rust.size || [...ts].some((operation) => !rust.has(operation))) {
    throw new Error(
      `mobile bridge operation mismatch: TypeScript=[${sortStrings([...ts]).join(",")}] Rust=[${sortStrings([...rust]).join(",")}]`,
    );
  }
  return {
    format: "convex-embedded-mobile-semantic-surface/v1",
    declarations: typescriptDeclarations([
      {
        file: "packages/embedded/src/expo/codec.ts",
        names: [
          "NativeEnvelope",
          "NativeResponse",
          "encodeRequest",
          "decodeRequest",
          "decodeResponse",
          "encodeMessage",
          "decodeMessage",
        ],
      },
      {
        file: "packages/embedded/src/expo/module.ts",
        names: ["NativeStoreObject", "NativeModule", "createNativeModuleLoader"],
      },
      { file: "packages/embedded/src/expo/store.ts", names: ["ExpoStoreBinding"] },
    ]),
    operations: sortStrings([...ts]),
    markers: markersIn("packages/embedded/src/expo/codec.ts"),
    implementation: implementationSources([
      "config/epoch.json",
      "packages/embedded/src/expo",
      "crates/mobile/include",
      "crates/mobile/src",
      "packages/embedded/android/src",
      "packages/embedded/ios",
    ]),
  };
}

