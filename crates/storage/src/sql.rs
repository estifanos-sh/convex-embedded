/// Rebuildable, candidate-owned physical layout. Changes here require a new package epoch and are
/// realized only in an unpublished generation.
pub(crate) fn generation_contract_manifest() -> Vec<String> {
    let mut manifest = generation_layout_manifest()
        .into_iter()
        .map(|statement| generation_sql(statement, 1).into_owned())
        .collect::<Vec<_>>();
    let probe = TableDef {
        name: "contract_probe".to_owned(),
        placement: TablePlacement::Device,
        columns: vec![
            ColumnDef {
                name: "first".to_owned(),
                field: None,
            },
            ColumnDef {
                name: "second".to_owned(),
                field: Some("nested.value".to_owned()),
            },
        ],
        crdt_fields: Vec::new(),
        local_fields: Vec::new(),
        indexes: Vec::new(),
    };
    manifest.push(generation_sql(&create_doc_table(&probe), 1).into_owned());
    manifest.push(
        generation_sql(
            &create_doc_index(
                &probe.name,
                "contract_index",
                &["first".to_owned(), "second".to_owned()],
            )
            .expect("the canonical layout probe uses valid identifiers"),
            1,
        )
        .into_owned(),
    );
    manifest
}

