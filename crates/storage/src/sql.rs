/// Read one table's arbitrary result-disclosed rows through its server-id index. Grouping by table
/// avoids the poor VALUES/LEFT JOIN plan used by some SQLite runtimes for large projection sets.
pub(crate) fn read_result_projections(count: usize) -> String {
    let values = std::iter::repeat_n("?", count)
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "SELECT {TABLE_NAME}, {SERVER_DOCUMENT_ID}, {DOCUMENT_ID}, \
         {CURRENT_REV_ID}, {PROJECTION_HASH}, {REV_ROOT_ID}, {REV_NODE_ID}, \
         {SERVER_BASE}, {SERVER_ROW}, {LOGICAL_CLOCK}, {UPDATED_TIME} \
         FROM {PROJECTIONS} WHERE {IDENTITY_KEY} = ? AND {TABLE_NAME} = ? \
         AND {SERVER_DOCUMENT_ID} IN ({values}) \
         ORDER BY {SERVER_DOCUMENT_ID}"
    )
}

