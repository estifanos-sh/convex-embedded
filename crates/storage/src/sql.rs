/// Batch originated records so large pull pages do not pay one interpreter/driver crossing per
/// membership edge. Callers keep chunks bounded to stay below SQLite's parameter limit.
pub(crate) fn write_origins(count: usize) -> String {
    let values = std::iter::repeat_n("(?, ?, ?, ?, ?, ?, ?, ?)", count)
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "INSERT INTO __embedded_origin \
         (generation, identity_key, kind, record_key, codec, flags, payload, payload_hash) \
         VALUES {values} \
         ON CONFLICT(generation, identity_key, kind, record_key) DO UPDATE SET \
         codec = excluded.codec, flags = excluded.flags, payload = excluded.payload, \
         payload_hash = excluded.payload_hash"
    )
}
