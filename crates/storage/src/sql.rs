fn all<I>(conditions: I) -> Cond
where
    I: IntoIterator,
    I::Item: IntoCondition,
{
    conditions
        .into_iter()
        .fold(Cond::all(), sea_query::Condition::add)
}

fn any<I>(conditions: I) -> Cond
where
    I: IntoIterator,
    I::Item: IntoCondition,
{
    conditions
        .into_iter()
        .fold(Cond::any(), sea_query::Condition::add)
}

fn merge(left: Cond, right: Cond) -> Cond {
    all([left, right])
}

#[cfg(test)]
mod generation_tests {
    use super::{generation_contract_manifest, generation_sql, kernel_layout_manifest};

    #[test]
    fn kernel_and_generation_contracts_are_separate() {
        let kernel = kernel_layout_manifest().join("\n");
        let generation = generation_contract_manifest().join("\n");
        assert!(kernel.contains("__embedded_bootstrap"));
        assert!(kernel.contains("__embedded_origin"));
        assert!(!kernel.contains("g1__"));
        assert!(generation.contains("g1__embedded_mutations"));
        assert!(generation.contains("g1__doc__contract_probe"));
        assert!(!generation.contains("__embedded_bootstrap"));
    }

    #[test]
    fn namespaces_mutable_identifiers_only_once() {
        assert_eq!(
            generation_sql(
                "SELECT * FROM __embedded_mutations INDEXED BY ux__embedded_commits__mutation",
                7,
            ),
            "SELECT * FROM g7__embedded_mutations INDEXED BY g7__ux__embedded_commits__mutation"
        );
        assert_eq!(
            generation_sql("SELECT * FROM g7__embedded_mutations", 7),
            "SELECT * FROM g7__embedded_mutations"
        );
        assert_eq!(
            generation_sql("SELECT * FROM doc__issues INDEXED BY ix__issues__by_id", 7),
            "SELECT * FROM g7__doc__issues INDEXED BY g7__ix__issues__by_id"
        );
        assert_eq!(
            generation_sql(
                "SELECT * FROM __embedded_projections INDEXED BY sqlite_autoindex___embedded_projections_1",
                7,
            ),
            "SELECT * FROM g7__embedded_projections INDEXED BY sqlite_autoindex_g7__embedded_projections_1"
        );
    }

    #[test]
    fn leaves_the_frozen_plane_unqualified() {
        assert_eq!(
            generation_sql(
                "SELECT value FROM __embedded_bootstrap; SELECT * FROM __embedded_origin; SELECT * FROM __embedded_origin_payload",
                3,
            ),
            "SELECT value FROM __embedded_bootstrap; SELECT * FROM __embedded_origin; SELECT * FROM __embedded_origin_payload"
        );
    }
}
